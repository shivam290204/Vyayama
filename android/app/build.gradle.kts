    signingConfigs {
        create("release") {
            keyAlias = keystoreProperties.getProperty("keyAlias")
            keyPassword = keystoreProperties.getProperty("keyPassword")
            storeFile = keystoreProperties.getProperty("storeFile")?.let {
                val f = rootProject.file(it)
                if (f.exists()) f else file(it)
            }
            storePassword = keystoreProperties.getProperty("storePassword")
        }
    }

    buildTypes {
        release {
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            val storeFileName = keystoreProperties.getProperty("storeFile")
            val keystoreFile = storeFileName?.let {
                val f = rootProject.file(it)
                if (f.exists()) f else file(it)
            }
            if (keystorePropertiesFile.exists() && keystoreFile != null && keystoreFile.exists()) {
                signingConfig = signingConfigs.getByName("release")
            } else {
                throw org.gradle.api.GradleException(
                    "Release signing failed: 'key.properties' or keystore file ('$storeFileName') is missing. Release build cannot use debug key."
                )
            }
        }
    }
}

