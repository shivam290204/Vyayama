import 'package:flutter/foundation.dart';

/// Normalized feature vector extracted from user activity logs.
///
/// Designed to feed future on-device ML models (e.g. TensorFlow Lite / ONNX)
/// or offline rule-based heuristic fallback models.
@immutable
class AdherenceFeatures {
  const AdherenceFeatures({
    required this.userId,
    required this.sessionsCompletedLast7Days,
    required this.sessionsScheduledLast7Days,
    required this.averageSessionDurationMinutes,
    required this.currentStreakDays,
    required this.averageReportedRpe,
    required this.skippedExercisesRatio,
    required this.daysSinceLastWorkout,
    required this.preferredWorkoutHour,
  });

  final String userId;

  /// Workouts marked complete in previous 7 days.
  final int sessionsCompletedLast7Days;

  /// Total workouts scheduled in previous 7 days.
  final int sessionsScheduledLast7Days;

  /// Mean completion time per completed session.
  final double averageSessionDurationMinutes;

  /// Consecutive active days.
  final int currentStreakDays;

  /// Mean Rate of Perceived Exertion (1 to 10 scale).
  final double averageReportedRpe;

  /// Ratio of exercises skipped within started workouts (0.0 to 1.0).
  final double skippedExercisesRatio;

  /// Days elapsed since last completed workout.
  final int daysSinceLastWorkout;

  /// Predominant hour of the day (0-23) when workouts occur.
  final int preferredWorkoutHour;

  /// Adherence rate over the trailing 7 days (0.0 - 1.0).
  double get trailing7DayAdherence {
    if (sessionsScheduledLast7Days <= 0) return 1.0;
    return (sessionsCompletedLast7Days / sessionsScheduledLast7Days).clamp(0.0, 1.0);
  }

  /// Converts features into a normalized float array for ML tensor input.
  List<double> toNormalizedTensor() {
    return [
      (sessionsCompletedLast7Days / 7.0).clamp(0.0, 1.0),
      trailing7DayAdherence,
      (averageSessionDurationMinutes / 90.0).clamp(0.0, 1.0),
      (currentStreakDays / 30.0).clamp(0.0, 1.0),
      (averageReportedRpe / 10.0).clamp(0.0, 1.0),
      skippedExercisesRatio.clamp(0.0, 1.0),
      (daysSinceLastWorkout / 14.0).clamp(0.0, 1.0),
      (preferredWorkoutHour / 24.0).clamp(0.0, 1.0),
    ];
  }
}

/// Output prediction generated by the adherence model.
@immutable
class AdherencePrediction {
  const AdherencePrediction({
    required this.churnRiskProbability,
    required this.recommendedIntensityAdjustment,
    required this.motivationalIntervention,
    required this.explanation,
  });

  /// Probability (0.0 to 1.0) that the user may lapse in workout frequency.
  final double churnRiskProbability;

  /// Suggested volume/intensity adjustment (-0.2 for -20%, +0.1 for +10%).
  final double recommendedIntensityAdjustment;

  /// Targeted nudge strategy (e.g., 'gentle_recovery', 'time_nudge', 'praise').
  final String motivationalIntervention;

  /// Rationale for coaches, mascots, or UI badges.
  final String explanation;
}

/// Abstract contract for workout adherence and churn prediction models.
///
/// Enables seamless future drop-in of on-device TFLite models while providing
/// a robust, deterministic baseline implementation today.
abstract interface class IAdherenceModel {
  Future<AdherencePrediction> predictAdherence(AdherenceFeatures features);
}

/// Baseline deterministic rule-based implementation of [IAdherenceModel].
class RuleBasedAdherenceModel implements IAdherenceModel {
  const RuleBasedAdherenceModel();

  @override
  Future<AdherencePrediction> predictAdherence(AdherenceFeatures features) async {
    // High fatigue / overtraining risk
    if (features.averageReportedRpe >= 8.5 && features.skippedExercisesRatio > 0.3) {
      return const AdherencePrediction(
        churnRiskProbability: 0.65,
        recommendedIntensityAdjustment: -0.15,
        motivationalIntervention: 'recovery_encouragement',
        explanation: 'Workouts may be too intense right now. Easing intensity by 15% preserves long-term habit formation.',
      );
    }

    // High momentum / strong habit formation
    if (features.trailing7DayAdherence >= 0.8 && features.currentStreakDays >= 3) {
      return const AdherencePrediction(
        churnRiskProbability: 0.10,
        recommendedIntensityAdjustment: 0.05,
        motivationalIntervention: 'milestone_praise',
        explanation: 'Strong consistency detected. Ready for steady progressive overload.',
      );
    }

    // Inactivity warning
    if (features.daysSinceLastWorkout >= 4) {
      return const AdherencePrediction(
        churnRiskProbability: 0.70,
        recommendedIntensityAdjustment: -0.10,
        motivationalIntervention: 'short_quick_session',
        explanation: 'A 10-minute quick restart workout can rebuild your momentum.',
      );
    }

    // Steady state baseline
    return const AdherencePrediction(
      churnRiskProbability: 0.25,
      recommendedIntensityAdjustment: 0.0,
      motivationalIntervention: 'standard_reminder',
      explanation: 'Maintaining current plan progression.',
    );
  }
}
